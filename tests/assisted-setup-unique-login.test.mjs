import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import crypto from 'node:crypto';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const server=read('server.mjs'),app=read('public/app.js'),traffic=read('public/traffic.html'),schema=read('db/schema.sql');
const slice=(start,end,haystack=server)=>{
  const first=haystack.indexOf(start),last=haystack.indexOf(end,first);
  assert.ok(first>=0&&last>first,'missing '+start);
  return haystack.slice(first,last);
};

test('new assisted setup user ID is unpredictable and globally unique in schema',()=>{
  const generated=server.match(/const newAssistedSetupLoginCode=\(\)=> 'RSP-'\+crypto\.randomBytes\(6\)\.toString\('hex'\)\.toUpperCase\(\);/);
  assert.ok(generated,'login ID is generated by cryptographic RNG');
  const make=new Function('crypto',generated[0]+'; return newAssistedSetupLoginCode;')(crypto);
  const sample=new Set(Array.from({length:100},make));
  assert.equal(sample.size,100);
  for(const value of sample)assert.match(value,/^RSP-[A-F0-9]{12}$/);
  assert.match(schema,/setup_login_code TEXT UNIQUE/);
  assert.match(server,/CREATE UNIQUE INDEX IF NOT EXISTS idx_users_setup_login_code ON users\(upper\(setup_login_code\)\) WHERE setup_login_code IS NOT NULL/);
});

test('login accepts either contact email or randomly issued code and still verifies the password',()=>{
  const code=slice("app.post('/api/auth/login'","app.post('/api/auth/password-reset/request'");
  assert.match(code,/lower\(email\)=lower\(\$1\) OR upper\(setup_login_code\)=upper\(\$1\)/);
  assert.match(code,/bcrypt\.compare\(req\.body\.password/);
  assert.match(code,/setSession\(res, r\.rows\[0\]\)/);
  assert.match(code,/Väärä tunnus tai salasana/);
  assert.doesNotMatch(code,/req\.body\.email\s*\|\|\s*req\.body\.password/);
});

test('manual setup assignment never overwrites customer billing contact email',()=>{
  const code=slice("app.post('/api/app/internal/setup-service-requests/:id/credentials'","// Owner confirms the customer has personally received their login details");
  assert.match(code,/auth, ownerTrafficOnly, loginLimiter/);
  assert.match(code,/FOR UPDATE OF sr,u/);
  assert.match(code,/job\.setup_login_code\|\|newAssistedSetupLoginCode\(\)/);
  assert.match(code,/UPDATE users SET setup_login_code=\$1,password_hash=\$2,session_version=session_version\+1/);
  assert.doesNotMatch(code,/UPDATE users SET email=/);
  assert.doesNotMatch(code,/req\.body\?\.email/);
  assert.match(code,/manualDeliveryRequired:true/);
  assert.match(code,/loginCode/);
  assert.match(code,/bcrypt\.hash\(password,12\)/);
  assert.match(code,/UPDATE password_reset_tokens SET used_at=NOW/);
});

test('owner sees the login code and a newly generated password without email administration',()=>{
  assert.match(traffic,/name="loginCode" type="text"/);
  assert.match(traffic,/readonly placeholder/);
  assert.match(traffic,/generateSetupPassword\(\);/);
  assert.match(traffic,/form\.elements\.loginCode\.value=result\.loginCode/);
  assert.match(traffic,/JSON\.stringify\(\{password\}\)/);
  assert.match(traffic,/\.mail\(form\.elements\.loginCode\.value\.trim\(\),form\.elements\.password\.value\)/);
  assert.match(traffic,/Kirjautumistunnus:/);
  assert.match(traffic,/Inloggnings-ID:/);
  assert.match(traffic,/Login ID:/);
  assert.doesNotMatch(slice('async function saveSetupCredentials','async function copySetupMessage',traffic),/form\.elements\.email/);
  assert.match(server,/u\.setup_login_code/);
});


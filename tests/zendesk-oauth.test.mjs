test('OAuth start persists one-time hashed state tied to tenant and owner, uses PKCE',async()=>{
  const calls=[];
  const db={query:async(sql,params)=>{calls.push([sql,params]);return {rows:[]};}};
  const result=await beginZendeskOAuth(db,TENANT,USER,'helpdesk.zendesk.com',config);
  const url=new URL(result.authorizationUrl);
  assert.equal(url.protocol,'https:');
  assert.equal(url.hostname,'helpdesk.zendesk.com');
  assert.equal(url.pathname,'/oauth/authorizations/new');
  assert.equal(url.searchParams.get('scope'),'tickets:read tickets:write');
  assert.equal(url.searchParams.get('response_type'),'code');
  assert.equal(url.searchParams.get('redirect_uri'),config.redirectUri);
  assert.equal(url.searchParams.get('code_challenge_method'),'S256');
  assert.ok(url.searchParams.get('code_challenge')?.length>40);
  assert.ok(url.searchParams.get('state')?.length>32);
  assert.equal(calls[0][1][1],TENANT);
  assert.equal(calls[0][1][2],USER);
  assert.notEqual(calls[0][1][0],url.searchParams.get('state'));
  assert.ok(!JSON.stringify(calls).includes(url.searchParams.get('state')));
});
test('token exchange rejects non-bearer and insufficient scopes',async()=>{
  const received=[];
  const fetchImpl=async(url,init)=>{received.push([url,init]);return providerResult(tokenResponse);};
  const token=await zendeskExchange('example',{
    grant_type:'authorization_code',code:'abc',client_id:'test',client_secret:'x'
  },{fetchImpl});
  assert.ok(token.expiresAt instanceof Date);
  assert.equal(received[0][0],'https://example.zendesk.com/oauth/tokens');
  assert.equal(received[0][1].redirect,'error');
  assert.match(received[0][1].body,/grant_type=authorization_code/);
  await assert.rejects(zendeskExchange('example',{grant_type:'authorization_code'},{
    fetchImpl:async()=>providerResult({...tokenResponse,scope:'tickets:read'})
  }),/required ticket scopes/);
  await assert.rejects(zendeskExchange('example',{grant_type:'authorization_code'},{
    fetchImpl:async()=>providerResult({...tokenResponse,token_type:'other'})
  }),/reusable OAuth/);
});
test('callback cannot replay state or cross workspaces and verifies actual ticket access',async()=>{
  const mockCalls=[];
  const verifier=zendeskTokenSeal('pkce-verifier-secret');
  const db={query:async(sql,args)=>{
    mockCalls.push([sql,args]);
    if(sql.includes('DELETE FROM respondo_zendesk_oauth_states')){
      return args[1]===TENANT&&args[2]===USER
        ?{rows:[{subdomain:'example',verifier_cipher:verifier}]}:{rows:[]};
    }
    return {rows:[]};
  }};
  const fetchImpl=async(url,init)=>{
    if(url.endsWith('/oauth/tokens'))return providerResult(tokenResponse);
    if(url.includes('/api/v2/tickets.json'))return providerResult({tickets:[]});
    throw Error('unexpected provider URL '+url);
  };
  const result=await completeZendeskOAuth(db,TENANT,USER,'opaque-state-abcdef','a-valid-authorization-code',
    config,{fetchImpl});
  assert.equal(result.connected,true);
  assert.equal(mockCalls.length,2);
  assert.ok(mockCalls.every(([,params])=>params[1]===TENANT));
  assert.ok(!JSON.stringify(mockCalls).includes('access-token-12345678'));
  await assert.rejects(completeZendeskOAuth(db,OTHER,USER,'opaque-state-abcdef','same-code',config,{fetchImpl}),TypeError);
});

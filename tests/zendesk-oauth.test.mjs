test('secrets use tenant-server AES-GCM, reject invalid ciphertext and never become plain text',()=>{
  const secret='a very secret token generated by Zendesk';
  const sealed=zendeskTokenSeal(secret);
  assert.ok(!sealed.includes(secret));
  assert.equal(zendeskTokenOpen(sealed),secret);
  assert.notEqual(zendeskTokenSeal(secret),sealed);
  assert.throws(()=>zendeskTokenOpen('aaa.bbb.ccc'));
  assert.throws(()=>zendeskTokenSeal('a'.repeat(10001)),TypeError);
});

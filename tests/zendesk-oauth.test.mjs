test('expired access uses refresh grant and rotates both ciphertexts',async()=>{
  const statements=[];
  const db={query:async(sql,args)=>{
    statements.push([sql,args]);
    if(sql.includes('FROM respondo_zendesk_connections')){
      return {rows:[{subdomain:'acme',access_cipher:zendeskTokenSeal('expired-access'),
        refresh_cipher:zendeskTokenSeal('old-refresh-12345'),access_expires_at:'2026-01-01T00:00:00Z'}]};
    }
    return {rowCount:1,rows:[{tenant_id:TENANT}]};
  }};
  const fresh=await usableZendeskAccess(db,TENANT,config,{
    fetchImpl:async(url,init)=>{
      assert.match(init.body,/grant_type=refresh_token/);
      return providerResult(tokenResponse);
    }
  });
  assert.equal(fresh.token,tokenResponse.access_token);
  const update=statements.find(x=>x[0].includes('UPDATE respondo_zendesk_connections'));
  assert.equal(update[1][0],TENANT);
  assert.notEqual(update[1][2],tokenResponse.access_token);
});
test('ticket exports require explicit approval and can be sent only once',async()=>{
  const statements=[],access=zendeskTokenSeal('live-access-token');
  let already=false,send=0;
  const db={query:async(sql,args)=>{
    statements.push([sql,args]);
    if(sql.includes('FROM respondo_native_tickets'))return {rows:[{
      id:TICKET,title:'Invoice question',details:'Customer requests a copy',priority:'normal'
    }]};
    if(sql.includes('INSERT INTO respondo_zendesk_exports'))return already?{rowCount:0,rows:[]}:{rowCount:1,rows:[]};
    if(sql.includes('SELECT status,external_ticket_id'))return {rows:[{status:'sent',external_ticket_id:'555'}]};
    if(sql.includes('FROM respondo_zendesk_connections'))return {rows:[{
      subdomain:'acme',access_cipher:access,refresh_cipher:zendeskTokenSeal('refresh-token'),
      access_expires_at:new Date(Date.now()+3600000)
    }]};
    return {rowCount:1,rows:[]};
  }};
  await assert.rejects(exportZendeskTicket(db,TENANT,TICKET,{approved:false,requesterEmail:'c@example.org'},config),TypeError);
  assert.equal(statements.length,0);
  const first=await exportZendeskTicket(db,TENANT,TICKET,{approved:true,requesterEmail:'c@example.org'},
    config,{fetchImpl:async(url,init)=>{
      send++;assert.equal(new URL(url).hostname,'acme.zendesk.com');
      const body=JSON.parse(init.body);
      assert.equal(body.ticket.requester.email,'c@example.org');
      return providerResult({ticket:{id:555}},201);
    }});
  assert.deepEqual(first,{status:'sent',externalTicketId:'555'});
  already=true;
  const again=await exportZendeskTicket(db,TENANT,TICKET,{approved:true,requesterEmail:'c@example.org'},
    config,{fetchImpl:async()=>{send++;throw Error('must not call provider');}});
  assert.equal(again.duplicate,true);
  assert.equal(send,1);
});
